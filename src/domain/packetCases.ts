// Facts taken from each case packet. Quotes are short spans from that PDF page.
// A missing page is unknown, never a pass.

import type { CaseElement, Cite, CriterionRow, ExtractRow } from "./caseRecord";

export interface PacketCase {
  file: string;
  title: string;
  summary: string;
  summaryCites: Cite[];
  elements: CaseElement[];
  flags: string[];
  extracted: ExtractRow[];
  criteria: CriterionRow[];
  policyLabel: string | null;
  policyHref: string | null;
  missing: string[];
}

const q = (page: number, quote: string): Cite => ({ docId: "packet", page, quote });
const el = (label: string, value: string, page: number, quote: string, mono = false): CaseElement => ({
  label,
  value,
  cite: q(page, quote),
  mono,
});
const row = (section: string, label: string, excerpt: string, page: number, quote: string): ExtractRow => ({
  section,
  label,
  excerpt,
  cite: q(page, quote),
});
const rule = (
  id: string,
  line: string,
  status: CriterionRow["status"],
  fact: string,
  detail: string,
  cites: Cite[],
): CriterionRow => ({ id, line, status, fact, detail, cites });

const library = (label: string): Pick<PacketCase, "policyLabel" | "policyHref"> => ({
  policyLabel: label,
  policyHref: "/settings",
});

